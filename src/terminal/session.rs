        reader
            .send(OutputEvent::Bytes(b"next burst".to_vec()))
            .unwrap();
        assert!(matches!(
            next_worker_event(&controls, &outputs, &notified, None).unwrap(),
            Some(WorkerEvent::Control(Command::OutputReady))
        ));
