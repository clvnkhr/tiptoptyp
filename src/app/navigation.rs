//! Owner-local source destinations. Search keeps its focus; navigation takes it.
use super::{
    DeferredDocumentAction, DocumentKind, char_index_at_line_column, line_column_at_char, same_path,
};
use crate::diagnostics::{Diagnostic, DiagnosticSource};
use std::{
    ops::Range,
    path::{Path, PathBuf},
};
use tiptoptyp_core::text::{LspRange, ScalarOffset, range_to_scalar_range};

use super::{EditorApp, EditorAttention, ViewMode};

#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) enum EditorSelection {
    Focus(Range<usize>),
    Search(Range<usize>),
}

impl EditorSelection {
    pub(super) fn range(&self) -> &Range<usize> {
        match self {
            Self::Focus(range) | Self::Search(range) => range,
        }
    }

    pub(super) fn takes_focus(&self) -> bool {
        matches!(self, Self::Focus(_))
    }
}

impl EditorApp {
    /// Source identity includes the owner of an untitled backing. Loading its
    /// generated bytes would create a second editable copy with a cache path.
    pub(super) fn source_tab_for_path(&self, path: &Path) -> Option<u64> {
        self.tabs.ids().find(|&id| {
            let Some(document) = self.document_for_tab(id) else {
                return false;
            };
            document
                .path()
                .as_deref()
                .is_some_and(|source| same_path(source, path))
                || (document.path().is_none()
                    && (same_path(&self.untitled_tab_path(id), path)
                        || (Some(id) == self.tabs.active_id()
                            && self
                                .tinymist_sync
                                .active_backing
                                .as_ref()
                                .is_some_and(|backing| same_path(backing.path(), path)))))
        })
    }

    fn is_current_source_path(&self, path: &Path) -> bool {
        self.document().path().as_deref().map_or_else(
            || same_path(&self.tinymist_document_path(), path),
            |current| same_path(current, path),
        )
    }

    fn original_source_destination(&self, path: PathBuf) -> Option<PathBuf> {
        // Normal diagnostics do not need tab scans or filesystem work to find
        // private ownership; the generated namespace is cheap to recognize.
        if !crate::private_workspace::is_generated_source_path(&path) {
            return Some(path);
        }
        if let Some(id) = self.source_tab_for_path(&path) {
            return Some(self.document_for_tab(id)?.path().clone().unwrap_or(path));
        }
        let canonical_path = path.canonicalize().ok();
        let mut roots = vec![self.tab_preview_root().to_owned(), self.project_root()];
        roots.extend(
            self.tabs
                .ids()
                .filter_map(|id| self.tab_workspace(id).map(Path::to_owned)),
        );
        for root in roots {
            // Try the workspace spelling first so removed mirrors still map;
            // canonical paths also cover macOS /var vs /private/var aliases.
            if let Some(original) = crate::private_workspace::original_mirrored_source(&root, &path)
            {
                return Some(original);
            }
            let root = root.canonicalize().unwrap_or(root);
            for candidate in std::iter::once(&path).chain(canonical_path.as_ref()) {
                if let Some(original) =
                    crate::private_workspace::original_mirrored_source(&root, candidate)
                {
                    return Some(original);
                }
            }
        }
        None
    }

    pub(super) fn diagnostic_targets_current_document(&self, diagnostic: &Diagnostic) -> bool {
        match &diagnostic.source {
            DiagnosticSource::Main => self.current_is_preview_document(),
            DiagnosticSource::File(_) => self
                .diagnostic_target_path(diagnostic)
                .is_some_and(|path| self.is_current_source_path(&path)),
            DiagnosticSource::Global => false,
        }
    }

    pub(super) fn diagnostic_target_path(&self, diagnostic: &Diagnostic) -> Option<PathBuf> {
        match &diagnostic.source {
            DiagnosticSource::Main => {
                self.original_source_destination(self.preview_document_path())
            }
            DiagnosticSource::File(path) if path.is_absolute() => {
                self.original_source_destination(path.clone())
            }
            DiagnosticSource::File(path) => {
                let preview_dir = self
                    .preview_document_path()
                    .parent()
                    .map(Path::to_path_buf)
                    .unwrap_or_else(|| self.project_root());
                let from_preview = preview_dir.join(path);
                // Resolve generated namespaces before checking existence: the
                // watcher may already have removed its private mirror.
                if crate::private_workspace::is_generated_source_path(&from_preview)
                    && let Some(original) = self.original_source_destination(from_preview.clone())
                {
                    return Some(original);
                }
                let candidate = if from_preview.exists() {
                    from_preview
                } else {
                    self.tab_preview_root().join(path)
                };
                self.original_source_destination(candidate)
            }
            DiagnosticSource::Global => None,
        }
    }

    pub(super) fn jump_to_diagnostic(&mut self, diagnostic: Diagnostic) {
        let Some(location) = diagnostic.location else {
            return;
        };
        if self.diagnostic_targets_current_document(&diagnostic) {
            if let Some(correction) = &diagnostic.correction
                && correction.is_current(self.document().key())
            {
                self.navigate_editor_range(correction.range.clone());
            } else {
                self.apply_editor_location(None, Some((location.line, location.column)));
            }
            return;
        }
        let Some(path) = self.diagnostic_target_path(&diagnostic) else {
            return;
        };
        self.navigate_file_location(
            path,
            None,
            Some((location.line, location.column)),
            "opening a diagnostic location",
        );
    }

    pub(super) fn navigate_file_location(
        &mut self,
        path: PathBuf,
        page: Option<usize>,
        source_position: Option<(usize, usize)>,
        description: &str,
    ) {
        if self.is_current_source_path(&path) {
            self.apply_file_link_location(page, source_position);
        } else {
            self.request_document_replacement(
                DeferredDocumentAction::FollowFileLink {
                    path,
                    page,
                    source_position,
                },
                description,
            );
        }
    }

    pub(super) fn apply_file_link_location(
        &mut self,
        page: Option<usize>,
        source_position: Option<(usize, usize)>,
    ) {
        let source_position = if self.document().config().is_some() {
            source_position.and_then(|(line, column)| {
                let snapshot = self.document().canonical_snapshot().ok()?;
                let cursor = char_index_at_line_column(snapshot.source(), line, column);
                let cursor = snapshot.editor_scalar_cursor(ScalarOffset::new(cursor))?;
                Some(line_column_at_char(snapshot.editor_source(), cursor.get()))
            })
        } else {
            source_position
        };
        self.apply_editor_location(page, source_position);
    }

    pub(super) fn apply_editor_location(
        &mut self,
        page: Option<usize>,
        source_position: Option<(usize, usize)>,
    ) {
        if self.document().kind() == DocumentKind::Pdf {
            if self.asset_preview.content.pdf().is_none() {
                self.pending_asset_page = page;
            } else if let Some(page) = page {
                self.pdfium_asset.go_to_page(page);
            }
        } else if self.document().kind().is_editable()
            && let Some((line, column)) = source_position
        {
            let char_index = char_index_at_line_column(self.document().source(), line, column);
            self.navigate_editor_range(char_index..char_index);
        }
    }

    pub(super) fn follow_tinymist_location(&mut self, uri: &str, selection: Option<&LspRange>) {
        let Ok(url) = url::Url::parse(uri) else {
            return;
        };
        let Ok(path) = url.to_file_path() else {
            return;
        };
        let Some(path) = self.original_source_destination(path) else {
            return;
        };
        if !self.is_current_source_path(&path) {
            if path
                .extension()
                .is_none_or(|extension| !extension.eq_ignore_ascii_case("typ"))
            {
                return;
            }
            self.request_document_replacement(
                DeferredDocumentAction::FollowTinymistLocation {
                    path,
                    selection: selection.cloned(),
                },
                "following the preview location",
            );
            return;
        }
        self.apply_tinymist_selection(selection);
    }

    pub(super) fn apply_tinymist_selection(&mut self, selection: Option<&LspRange>) {
        if let Some(selection) = selection {
            let range = if self.document().config().is_some() {
                let Some(range) = self
                    .document()
                    .canonical_snapshot()
                    .ok()
                    .and_then(|snapshot| snapshot.editor_range(*selection))
                else {
                    return;
                };
                range
            } else {
                range_to_scalar_range(self.document().source(), selection).into_range()
            };
            self.navigate_editor_range(range);
        }
        self.view_mode = ViewMode::Split;
    }

    pub(super) fn navigate_editor_range(&mut self, range: Range<usize>) {
        self.editor_attention = Some(EditorAttention::arm(range.start));
        self.pending_editor_selection = Some(EditorSelection::Focus(range));
        self.find_bar.focus = false;
        if self.document().kind().is_typst() {
            self.view_mode = ViewMode::Split;
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        diagnostics::{DiagnosticLocation, DiagnosticSeverity},
        private_workspace::PrivateWorkspace,
    };

    fn diagnostic(path: PathBuf) -> Diagnostic {
        Diagnostic {
            correction: None,
            provider: None,
            severity: DiagnosticSeverity::Error,
            source: DiagnosticSource::File(path),
            location: Some(DiagnosticLocation { line: 2, column: 3 }),
            message: "fixture error".into(),
            details: Vec::new(),
        }
    }

    #[test]
    fn problems_generated_main_location_keeps_the_original_editor_tab() {
        let root = tempfile::tempdir().unwrap();
        let context = eframe::egui::Context::default();
        let mut app = EditorApp::dormant_for_tests(&context, root.path().into());
        let original = root.path().join("main.typ");
        app.document_mut()
            .replace_unprojected_untitled("first\nsecond line\n");
        app.document_mut()
            .rename(original.clone(), DocumentKind::Typst)
            .unwrap();
        std::fs::write(&original, app.document().source()).unwrap();
        let mirror = PrivateWorkspace::open(root.path())
            .unwrap()
            .mirrored_source(root.path(), "main.typ", app.document().source())
            .unwrap();
        let generated = mirror
            .path()
            .strip_prefix(root.path().canonicalize().unwrap())
            .unwrap()
            .to_owned();
        app.jump_to_diagnostic(diagnostic(generated));
        assert_eq!(app.document().path().as_ref(), Some(&original));
        assert_eq!(app.tabs.len(), 1);
        assert!(
            app.pending_editor_selection.is_some(),
            "Problems should select the original source location"
        );
        assert!(
            app.document_workflow.take_action().is_none(),
            "Problems must never queue the generated source for opening"
        );
    }

    #[test]
    fn generated_diagnostic_keeps_projected_unicode_editor_offsets() {
        use crate::diagnostics::DiagnosticReport;
        use tiptoptyp::mitex_projection::Config;
        let root = tempfile::tempdir().unwrap();
        let context = eframe::egui::Context::default();
        let mut app = EditorApp::dormant_for_tests(&context, root.path().into());
        let canonical = "#import \"@preview/mitex:0.2.7\": mi\n文 #mi(`\\alpha+😀`) tail\n";
        let original = root.path().join("main.typ");
        std::fs::write(&original, canonical).unwrap();
        app.document_mut().replace_unprojected_untitled(canonical);
        app.document_mut()
            .rename(original, DocumentKind::Typst)
            .unwrap();
        app.document_mut().enable(Config::default()).unwrap();
        let mirror = PrivateWorkspace::open(root.path())
            .unwrap()
            .mirrored_source(root.path(), "main.typ", canonical)
            .unwrap();
        let canonical_cursor = canonical[..canonical.find("tail").unwrap()].chars().count();
        let (line, column) = line_column_at_char(canonical, canonical_cursor);
        let mut diagnostic = diagnostic(mirror.path().to_owned());
        diagnostic.location = Some(DiagnosticLocation { line, column });
        app.set_diagnostics(DiagnosticReport {
            raw: String::new(),
            diagnostics: vec![diagnostic],
        });
        let cursor = app.document().source()[..app.document().source().find("tail").unwrap()]
            .chars()
            .count();
        let expected = line_column_at_char(app.document().source(), cursor);
        let diagnostic = app.preview.diagnostics[0].clone();
        assert_eq!(
            diagnostic.location.map(|p| (p.line, p.column)),
            Some(expected)
        );
        app.jump_to_diagnostic(diagnostic);
        assert_eq!(
            app.pending_editor_selection,
            Some(EditorSelection::Focus(cursor..cursor))
        );
        assert_eq!(app.tabs.len(), 1);
        assert!(app.document_workflow.take_action().is_none());
    }

    #[test]
    fn opening_a_known_unsaved_backing_activates_its_owner_without_loading_the_copy() {
        let root = tempfile::tempdir().unwrap();
        let context = eframe::egui::Context::default();
        let mut app = EditorApp::dormant_for_tests(&context, root.path().into());
        app.lifecycle = super::super::DocumentLifecycle::Active;
        app.document_mut()
            .replace_unprojected_untitled("first untitled buffer");
        let first = app.tabs.active_id().unwrap();
        app.new_tab(&context);
        app.prepare_tab_backings().unwrap();
        let backing = app.tinymist_sync.tab_backings[&first].path().to_owned();
        let count = app.tabs.len();
        assert!(app.open_tab_path(backing, &context));
        assert_eq!(app.tabs.active_id(), Some(first));
        assert_eq!(app.tabs.len(), count);
        assert!(
            app.document().path().is_none(),
            "generated storage must not become the tab's save path"
        );
        assert_eq!(app.document().source(), "first untitled buffer");
    }

    #[test]
    fn diagnostics_cannot_open_an_unowned_generated_document() {
        let root = tempfile::tempdir().unwrap();
        let context = eframe::egui::Context::default();
        let mut app = EditorApp::dormant_for_tests(&context, root.path().into());
        app.jump_to_diagnostic(diagnostic(
            root.path().join(".tiptoptyp/documents/stale.typ"),
        ));
        assert!(
            app.document_workflow.take_action().is_none(),
            "a stale generated diagnostic is not an editable source destination"
        );
        assert_eq!(app.tabs.len(), 1);
    }
}
